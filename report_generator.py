def generate_full_csv_export(
    inspections_list: List[Dict[str, Any]],
    output_path: str,
) -> str:
    """
    Generate a complete CSV export file from a list of inspection records.

    Args:
        inspections_list: list of inspection dicts
        output_path: path where the .csv file should be saved

    Returns:
        The output_path on success.
    """
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    headers = CSV_COLUMNS + ["image_path", "overlay_path", "report_path"]

    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=headers, extrasaction="ignore")
        writer.writeheader()
        for record in inspections_list:
            writer.writerow(record)

    return output_path
